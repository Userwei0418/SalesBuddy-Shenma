"""Backup security comparison normalizes defaults without hiding real privilege changes."""
import importlib.util
from pathlib import Path
import sys
from uuid import uuid4

import pytest

from tests.integration.feishu_fixtures import fixture_owner

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'tools/local'))
spec=importlib.util.spec_from_file_location('recovery_acl_test',ROOT/'tools/local/recovery.py')
recovery=importlib.util.module_from_spec(spec);spec.loader.exec_module(recovery)
pytestmark=pytest.mark.asyncio


async def test_default_owner_acl_equals_explicit_owner_but_public_read_is_detected(connection):
    name='recovery_acl_'+uuid4().hex
    async with fixture_owner(connection):
        await connection.execute('CREATE TABLE config.'+name+'(id integer)')
        async def entry():
            items=(await recovery.security_inventory(connection))['tables']
            return next(r for r in items if r['nspname']=='config' and r['relname']==name)
        before=await entry()
        await connection.execute('GRANT SELECT ON config.'+name+' TO PUBLIC')
        assert await entry()!=before
        await connection.execute('REVOKE ALL ON config.'+name+' FROM PUBLIC')
        assert await entry()==before


async def test_default_function_execute_is_not_confused_with_revoked_public(connection):
    name='recovery_function_'+uuid4().hex
    async with fixture_owner(connection):
        await connection.execute('CREATE FUNCTION config.'+name+'() RETURNS integer LANGUAGE sql AS $$ SELECT 1 $$')
        await connection.execute('GRANT EXECUTE ON FUNCTION config.'+name+'() TO PUBLIC')
        async def entry():
            items=(await recovery.security_inventory(connection))['functions']
            return next(r for r in items if r['nspname']=='config' and r['proname']==name)
        before=await entry()
        await connection.execute('REVOKE EXECUTE ON FUNCTION config.'+name+'() FROM PUBLIC')
        assert await entry()!=before


async def test_recovery_rejects_sequence_that_would_reuse_a_restored_id(connection):
    name='recovery_sequence_'+uuid4().hex
    async with fixture_owner(connection):
        await connection.execute('CREATE TABLE config.'+name+'(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)')
        await connection.execute('INSERT INTO config.'+name+' DEFAULT VALUES')
        await recovery.verify_sequence_positions(connection)
        await connection.execute('ALTER TABLE config.'+name+' ALTER COLUMN id RESTART WITH 1')
        with pytest.raises(recovery.RecoveryError,match='reuse'):
            await recovery.verify_sequence_positions(connection)
