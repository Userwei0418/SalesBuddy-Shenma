CREATE FUNCTION control.configuration_status(p_session text,p_workspace uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE report jsonb; policy jsonb; facts jsonb; owned boolean; models jsonb:='[]';
BEGIN
 report:=control.configuration_status_before_ai_service(p_session,p_workspace);
 policy:=control.ai_service_settings(p_session,p_workspace);
 FOR facts IN SELECT * FROM jsonb_array_elements(report->'model_connections') LOOP
  owned:=false;
  IF facts->>'source'='tenant_purpose' THEN
   SELECT EXISTS(SELECT 1 FROM config.model_api_current c JOIN config.model_api_release r USING(workspace_id,purpose,version_no)
    JOIN config.model_api_test t ON t.workspace_id=r.workspace_id AND t.id=r.test_id
    WHERE c.workspace_id=p_workspace AND c.purpose=facts->>'purpose' AND t.source_guard IS NULL
     AND octet_length(r.api_key_ciphertext)>0) INTO owned;
  ELSIF facts->>'source'='tenant_legacy' THEN
   owned:=(facts->>'fields_present')::boolean AND (facts->>'credential_saved')::boolean;
  END IF;
  models:=models||jsonb_build_array(facts||jsonb_build_object('credential_owned',owned,'service_authorized',
   facts->>'mode' NOT IN ('disabled','invalid') AND ((policy->>'shared_enabled')::boolean OR owned)));
 END LOOP;
 PERFORM control.require_actor(p_session);
 RETURN report||jsonb_build_object('ai_service',policy,'model_connections',models);
END $$;
