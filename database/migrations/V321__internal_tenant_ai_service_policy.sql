-- The request snapshot is generated by the server. For company-owned sources,
-- independently verify the exact current release/test and credential origin.
CREATE FUNCTION security.assert_ai_service_source(p_invocation uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE ws uuid:=common.current_workspace_id(); i agent.model_invocation; enabled boolean; valid boolean:=false; selected_purpose text;
BEGIN
 SELECT * INTO i FROM agent.model_invocation WHERE id=p_invocation AND workspace_id=ws
 AND actor_user_ref_id=common.current_user_ref_id() AND actor_role_code=current_setting('app.role_code',true);
 IF NOT FOUND OR NOT security.workspace_is_active(ws) THEN
  RAISE EXCEPTION 'AI_SERVICE_CONTEXT_REQUIRED' USING ERRCODE='42501'; END IF;
 -- Serialize admission/dispatch with a platform revocation. No lock spans HTTP.
 SELECT shared_enabled INTO enabled FROM control.tenant_ai_service WHERE workspace_id=ws FOR SHARE;
 IF enabled IS TRUE THEN RETURN; END IF;
 selected_purpose:=CASE i.endpoint_code WHEN '/v1/chat/completions' THEN 'text'
  WHEN '/v1/audio/transcriptions' THEN 'asr' WHEN '/v1/t2a_v2' THEN 'tts' END;
 IF selected_purpose IS NOT NULL AND i.request_snapshot->>'connection_purpose'=selected_purpose THEN
  CASE i.request_snapshot->>'ai_service_source'
  WHEN 'tenant_purpose' THEN
   SELECT EXISTS(SELECT 1 FROM config.model_api_current c
    JOIN config.model_api_release r USING(workspace_id,purpose,version_no)
    JOIN config.model_api_test t ON t.workspace_id=r.workspace_id AND t.id=r.test_id
    WHERE c.workspace_id=ws AND c.purpose=selected_purpose AND c.version_no::text=i.request_snapshot->>'connection_version'
     AND r.config_snapshot->>'mode'='custom' AND octet_length(r.api_key_ciphertext)>0 AND t.source_guard IS NULL) INTO valid;
  WHEN 'tenant_legacy' THEN
   SELECT EXISTS(SELECT 1 FROM config.agent_runtime_config l WHERE l.workspace_id=ws AND l.enabled
    AND l.revision_no::text=i.request_snapshot->>'connection_version' AND octet_length(l.api_key_ciphertext)>0
    AND length(btrim(l.provider_base_url))>0 AND length(btrim(CASE selected_purpose WHEN 'text' THEN l.llm_model
     WHEN 'asr' THEN l.asr_model ELSE l.tts_model END))>0) INTO valid;
  WHEN 'tenant_test' THEN
   SELECT EXISTS(SELECT 1 FROM config.model_api_test t WHERE t.workspace_id=ws
    AND t.id::text=i.request_snapshot->>'connection_test_id' AND t.id::text=i.operation_id::text
    AND i.operation_code='model_connection_test' AND t.actor_user_ref_id=common.current_user_ref_id()
    AND t.purpose=selected_purpose AND t.status='running' AND t.expires_at>clock_timestamp()
    AND t.config_snapshot->>'mode'='custom' AND octet_length(t.api_key_ciphertext)>0 AND t.source_guard IS NULL) INTO valid;
  ELSE NULL;
  END CASE;
 END IF;
 IF valid IS NOT TRUE THEN RAISE EXCEPTION 'TENANT_SHARED_AI_DISABLED' USING ERRCODE='P7432'; END IF;
END $$;

CREATE OR REPLACE FUNCTION security.reserve_model_call(p_invocation uuid,p_receipt uuid) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE ws uuid:=common.current_workspace_id(); actor uuid:=common.current_user_ref_id();
 i agent.model_invocation; q control.tenant_call_quota; e control.call_event; a control.call_attempt;
 resource_code text; logical_id uuid; job_event uuid; job_id uuid:=NULLIF(current_setting('app.job_id',true),'')::uuid; boundary timestamptz; consumed bigint;
BEGIN
 PERFORM security.assert_ai_service_source(p_invocation);
 IF ws IS NULL OR actor IS NULL OR p_receipt IS NULL OR NOT security.workspace_is_active(ws) THEN
  RAISE EXCEPTION 'CALL_RESERVATION_DENIED' USING ERRCODE='42501'; END IF;
 SELECT * INTO i FROM agent.model_invocation WHERE id=p_invocation AND workspace_id=ws
  AND actor_user_ref_id=actor AND actor_role_code=current_setting('app.role_code',true)
  AND record_kind='provider_attempt' AND status='running';
 IF NOT FOUND THEN RAISE EXCEPTION 'CALL_RESERVATION_DENIED' USING ERRCODE='42501'; END IF;
 resource_code:=CASE i.endpoint_code WHEN '/v1/audio/transcriptions' THEN 'asr_calls'
  WHEN '/v1/chat/completions' THEN 'ai_calls' WHEN 'agent-chat-messages' THEN 'ai_calls'
  WHEN '/v1/t2a_v2' THEN 'tts_calls' END;
 IF job_id IS NOT NULL THEN
  SELECT CASE WHEN (j.job_type,j.aggregate_type) IN (
    ('agent.run','agent_run'),('visit.import','visit_import'),
    ('business.advice','business_advice'),('sales_competency.review','sales_competency_review'),
    ('customer.risk.review','customer_risk_assessment'),
    ('opportunity.change.review','business_change'),('ai.connectivity','ai_connectivity'))
   THEN COALESCE(j.aggregate_id,j.id) ELSE j.id END
   INTO job_event FROM ops.job j WHERE j.id=job_id AND j.workspace_id=ws
   AND j.status='running' AND j.locked_until>clock_timestamp();
  IF NOT FOUND THEN RAISE EXCEPTION 'CALL_JOB_LEASE_INVALID' USING ERRCODE='P7409'; END IF;
 END IF;
 logical_id:=COALESCE(i.run_id,job_event,i.operation_id);
 IF resource_code IS NULL OR logical_id IS NULL OR COALESCE(length(i.operation_code),0) NOT BETWEEN 1 AND 100 THEN
  RAISE EXCEPTION 'INVALID_CALL_OPERATION' USING ERRCODE='P7422'; END IF;
 SELECT * INTO q FROM control.tenant_call_quota WHERE workspace_id=ws AND resource=resource_code FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'CALL_QUOTA_NOT_INITIALIZED' USING ERRCODE='P7500'; END IF;
 SELECT * INTO a FROM control.call_attempt WHERE invocation_id=p_invocation;
 IF FOUND THEN
  IF a.receipt IS DISTINCT FROM p_receipt OR a.workspace_id<>ws OR a.state<>'reserved' THEN
   RAISE EXCEPTION 'CALL_ATTEMPT_CONFLICT' USING ERRCODE='P7409'; END IF;
  RETURN a.state;
 END IF;
 SELECT * INTO e FROM control.call_event WHERE workspace_id=ws AND resource=resource_code
  AND operation_code=i.operation_code AND event_id=logical_id;
 IF FOUND AND e.actor_id<>actor THEN RAISE EXCEPTION 'CALL_EVENT_CONFLICT' USING ERRCODE='P7409'; END IF;
 IF e.state IS NULL OR e.state='released' THEN
  boundary:=CASE q.period WHEN 'month_utc' THEN date_trunc('month',clock_timestamp() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC' ELSE '-infinity'::timestamptz END;
  IF q.call_limit IS NOT NULL THEN
   SELECT count(*) INTO consumed FROM control.call_event WHERE workspace_id=ws AND resource=resource_code
    AND created_at>=boundary AND state IN ('reserved','used');
   IF consumed>=q.call_limit THEN RAISE EXCEPTION 'TENANT_CALL_QUOTA_EXCEEDED' USING ERRCODE='P7431'; END IF;
  END IF;
  INSERT INTO control.call_event(workspace_id,resource,operation_code,event_id,actor_id,state)
   VALUES(ws,resource_code,i.operation_code,logical_id,actor,'reserved')
   ON CONFLICT(workspace_id,resource,operation_code,event_id) DO UPDATE SET state='reserved',created_at=clock_timestamp();
 END IF;
 INSERT INTO control.call_attempt(invocation_id,workspace_id,resource,operation_code,event_id,receipt,state)
 VALUES(p_invocation,ws,resource_code,i.operation_code,logical_id,p_receipt,'reserved');
 RETURN 'reserved';
END $$;

CREATE OR REPLACE FUNCTION security.dispatch_model_call(p_invocation uuid,p_receipt uuid) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE a control.call_attempt;
BEGIN
 PERFORM security.assert_ai_service_source(p_invocation);
 SELECT * INTO a FROM control.call_attempt WHERE invocation_id=p_invocation;
 IF NOT FOUND OR p_receipt IS NULL OR a.receipt IS DISTINCT FROM p_receipt
  OR a.workspace_id IS DISTINCT FROM common.current_workspace_id()
  OR NOT security.workspace_is_active(a.workspace_id)
  OR NOT EXISTS(SELECT 1 FROM control.call_event e WHERE e.workspace_id=a.workspace_id AND e.resource=a.resource
   AND e.operation_code=a.operation_code AND e.event_id=a.event_id AND e.actor_id=common.current_user_ref_id()) THEN
  RAISE EXCEPTION 'CALL_DISPATCH_DENIED' USING ERRCODE='42501'; END IF;
 UPDATE control.call_attempt SET state='dispatched',updated_at=clock_timestamp()
 WHERE invocation_id=p_invocation AND state='reserved';
 IF NOT FOUND THEN RAISE EXCEPTION 'CALL_ALREADY_DISPATCHED' USING ERRCODE='P7409'; END IF;
 RETURN true;
END $$;

