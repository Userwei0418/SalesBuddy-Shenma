#!/usr/bin/env python3
"""Reuse the page's existing theme on root-portal content; no token changes."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / 'miniprogram'
SOURCES = ('ui/design-tokens.wxss', 'ui/bridge-tdesign.wxss', 'styles/theme-blue-black-white.wxss')
TARGET = ROOT / 'styles/portal-theme.wxss'


def render():
    declarations = {}
    for name in SOURCES:
        source = (ROOT / name).read_text()
        blocks = re.findall(r'(?m)^page\s*\{([^}]+)\}', source)
        if not blocks:
            raise ValueError(f'Missing page theme: {name}')
        for block in blocks:
            declarations.update(re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', block))
    if '--ui-page-gutter' not in declarations or '--td-brand-color' not in declarations:
        raise ValueError('Incomplete portal theme')
    return ('/* Generated by scripts/generate_portal_theme.py from existing page tokens.\n'
            ' * root-portal is outside page and does not inherit those variables. */\n'
            '.sb-portal-theme {\n' + ''.join(f'  {key}: {value};\n' for key,value in declarations.items()) +
            '  font-family: var(--ui-font);\n  font-size: var(--ui-text-body);\n  color: var(--ui-ink);\n}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('Portal theme differs; run frontend/scripts/generate_portal_theme.py')
    else:
        TARGET.write_text(expected)
